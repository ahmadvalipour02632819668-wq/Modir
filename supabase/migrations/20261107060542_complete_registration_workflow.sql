
alter table public.registration_requests
  add column if not exists manager_is_resident boolean not null default false,
  add column if not exists manager_unit_no integer,
  add column if not exists manager_area numeric(10,2),
  add column if not exists manager_persons integer,
  add column if not exists manager_start_date_jalali text;

alter table public.accounts
  add column if not exists start_date_jalali text;

create table if not exists public.membership_registration_requests (
  id bigint generated by default as identity primary key,
  building_id integer not null references public.buildings(id) on delete cascade,
  unit_no integer not null,
  occupancy text not null check (occupancy in ('مالک ساکن','مالک','مستأجر')),
  username text not null,
  password_hash text not null,
  full_name text not null,
  phone text,
  email text,
  area numeric(10,2) not null check (area > 0),
  persons integer,
  start_date_jalali text not null,
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  reviewed_at timestamptz,
  reviewed_by uuid,
  created_at timestamptz not null default now(),
  constraint membership_registration_persons_check
    check ((occupancy='مالک' and persons is null) or (occupancy<>'مالک' and persons between 1 and 30))
);

create index if not exists membership_registration_pending_idx
  on public.membership_registration_requests(building_id,unit_no,occupancy)
  where status='pending';

alter table public.membership_registration_requests enable row level security;
revoke all on public.membership_registration_requests from anon, authenticated;
grant usage, select on sequence public.membership_registration_requests_id_seq to service_role;

create or replace function public.app_submit_registration(
 p_building_name text,p_address text,p_username text,p_password text,p_full_name text,
 p_phone text,p_email text,p_units_count integer,p_manager_is_resident boolean,
 p_manager_unit_no integer,p_manager_area numeric,p_manager_persons integer,p_manager_start_date_jalali text
) returns jsonb
language plpgsql security definer
set search_path=pg_catalog,public,extensions
as $$
declare v_id bigint;
begin
 if coalesce(trim(p_building_name),'')='' or coalesce(trim(p_address),'')='' or coalesce(trim(p_full_name),'')='' or coalesce(trim(p_phone),'')='' then
  return jsonb_build_object('ok',false,'error','اطلاعات ضروری را کامل کنید');
 end if;
 if p_username !~ '^[A-Za-z][A-Za-z0-9_]{2,31}$' then
  return jsonb_build_object('ok',false,'error','نام کاربری باید با حرف انگلیسی شروع شود و فقط شامل حروف، عدد و زیرخط باشد (۳ تا ۳۲ نویسه)');
 end if;
 if p_password !~ '^[0-9]{4,8}$' then
  return jsonb_build_object('ok',false,'error','رمز عبور باید ۴ تا ۸ رقم باشد');
 end if;
 if p_units_count not between 1 and 10 then
  return jsonb_build_object('ok',false,'error','تعداد واحدهای ساختمان باید بین ۱ تا ۱۰ باشد');
 end if;
 if p_manager_is_resident and (
   p_manager_unit_no not between 1 and p_units_count or coalesce(p_manager_area,0)<=0
   or coalesce(p_manager_persons,0) not between 1 and 30
   or p_manager_start_date_jalali !~ '^[0-9]{4}/(0[1-9]|1[0-2])/([0-2][0-9]|3[01])$'
 ) then
  return jsonb_build_object('ok',false,'error','اطلاعات سکونت مدیر کامل یا معتبر نیست');
 end if;
 if exists(select 1 from public.accounts where lower(username)=lower(p_username))
  or exists(select 1 from public.registration_requests where lower(username)=lower(p_username) and status='pending')
  or exists(select 1 from public.membership_registration_requests where lower(username)=lower(p_username) and status='pending') then
  return jsonb_build_object('ok',false,'error','این نام کاربری قبلاً استفاده شده یا در انتظار تأیید است');
 end if;
 insert into public.registration_requests(building_name,address,username,password_hash,full_name,phone,email,units_count,
   manager_is_resident,manager_unit_no,manager_area,manager_persons,manager_start_date_jalali)
 values(trim(p_building_name),trim(p_address),trim(p_username),extensions.crypt(p_password,extensions.gen_salt('bf')),
   trim(p_full_name),nullif(trim(p_phone),''),nullif(trim(p_email),''),p_units_count,
   coalesce(p_manager_is_resident,false),case when p_manager_is_resident then p_manager_unit_no end,
   case when p_manager_is_resident then p_manager_area end,case when p_manager_is_resident then p_manager_persons end,
   case when p_manager_is_resident then p_manager_start_date_jalali end)
 returning id into v_id;
 return jsonb_build_object('ok',true,'request_id',v_id,'message','درخواست ایجاد ساختمان برای بررسی سوپرادمین ارسال شد');
end $$;

create or replace function public.app_submit_member_registration(
 p_building_id integer,p_unit_no integer,p_occupancy text,p_username text,p_password text,
 p_full_name text,p_phone text,p_email text,p_area numeric,p_persons integer,p_start_date_jalali text
) returns jsonb
language plpgsql security definer
set search_path=pg_catalog,public,extensions
as $$
declare v_id bigint; v_units integer;
begin
 if p_occupancy not in ('مالک ساکن','مالک','مستأجر') then
  return jsonb_build_object('ok',false,'error','نوع ثبت‌نام نامعتبر است');
 end if;
 if p_username !~ '^[A-Za-z][A-Za-z0-9_]{2,31}$' or p_password !~ '^[0-9]{4,8}$' then
  return jsonb_build_object('ok',false,'error','نام کاربری یا رمز عبور با قواعد سامانه مطابقت ندارد');
 end if;
 if coalesce(trim(p_full_name),'')='' or coalesce(trim(p_phone),'')='' or coalesce(p_area,0)<=0
  or p_start_date_jalali !~ '^[0-9]{4}/(0[1-9]|1[0-2])/([0-2][0-9]|3[01])$' then
  return jsonb_build_object('ok',false,'error','اطلاعات ضروری یا تاریخ شمسی معتبر نیست');
 end if;
 if p_occupancy<>'مالک' and coalesce(p_persons,0) not between 1 and 30 then
  return jsonb_build_object('ok',false,'error','تعداد ساکنان باید بین ۱ تا ۳۰ نفر باشد');
 end if;
 select count(*) into v_units from public.units where building_id=p_building_id;
 if not exists(select 1 from public.buildings where id=p_building_id and status='active')
   or p_unit_no not between 1 and v_units then
  return jsonb_build_object('ok',false,'error','ساختمان یا شماره واحد معتبر نیست');
 end if;
 if exists(select 1 from public.accounts where lower(username)=lower(p_username))
  or exists(select 1 from public.registration_requests where lower(username)=lower(p_username) and status='pending')
  or exists(select 1 from public.membership_registration_requests where lower(username)=lower(p_username) and status='pending') then
  return jsonb_build_object('ok',false,'error','این نام کاربری قبلاً استفاده شده یا در انتظار تأیید است');
 end if;
 if p_occupancy='مالک ساکن' and exists(select 1 from public.accounts where building_id=p_building_id and unit_no=p_unit_no)
  or p_occupancy='مالک' and exists(select 1 from public.accounts where building_id=p_building_id and unit_no=p_unit_no and occupancy in ('مالک','مالک ساکن'))
  or p_occupancy='مستأجر' and exists(select 1 from public.accounts where building_id=p_building_id and unit_no=p_unit_no and occupancy in ('مستأجر','مالک ساکن')) then
  return jsonb_build_object('ok',false,'error','با توجه به ترکیب مالک و مستأجر موجود در این واحد، این ثبت‌نام مجاز نیست');
 end if;
 if p_occupancy='مالک ساکن' and exists(select 1 from public.membership_registration_requests where building_id=p_building_id and unit_no=p_unit_no and status='pending')
  or p_occupancy='مالک' and exists(select 1 from public.membership_registration_requests where building_id=p_building_id and unit_no=p_unit_no and status='pending' and occupancy in ('مالک','مالک ساکن'))
  or p_occupancy='مستأجر' and exists(select 1 from public.membership_registration_requests where building_id=p_building_id and unit_no=p_unit_no and status='pending' and occupancy in ('مستأجر','مالک ساکن')) then
  return jsonb_build_object('ok',false,'error','برای این واحد درخواست متعارضی در انتظار بررسی است');
 end if;
 insert into public.membership_registration_requests(building_id,unit_no,occupancy,username,password_hash,full_name,phone,email,area,persons,start_date_jalali)
 values(p_building_id,p_unit_no,p_occupancy,trim(p_username),extensions.crypt(p_password,extensions.gen_salt('bf')),
 trim(p_full_name),nullif(trim(p_phone),''),nullif(trim(p_email),''),p_area,
 case when p_occupancy='مالک' then null else p_persons end,p_start_date_jalali)
 returning id into v_id;
 return jsonb_build_object('ok',true,'request_id',v_id,'message','درخواست عضویت برای تأیید مدیر ساختمان ارسال شد');
end $$;

create or replace function public.app_admin_list_membership_registrations(p_token uuid)
returns jsonb language plpgsql stable security definer set search_path=public
as $$
declare me public.accounts;
begin
 me:=public.bm_admin(p_token);
 return coalesce((select jsonb_agg(jsonb_build_object(
  'id',r.id,'unit_no',r.unit_no,'occupancy',r.occupancy,'username',r.username,'full_name',r.full_name,
  'phone',r.phone,'email',r.email,'area',r.area,'persons',r.persons,'start_date_jalali',r.start_date_jalali,'created_at',r.created_at
 ) order by r.created_at) from public.membership_registration_requests r
 where r.building_id=me.building_id and r.status='pending'),'[]'::jsonb);
end $$;

create or replace function public.app_admin_review_membership_registration(p_token uuid,p_request_id bigint,p_decision text)
returns jsonb language plpgsql security definer set search_path=public,extensions
as $$
declare me public.accounts; r public.membership_registration_requests; v_start integer; v_id uuid;
begin
 me:=public.bm_admin(p_token);
 if p_decision not in ('approve','reject') then return jsonb_build_object('ok',false,'error','تصمیم نامعتبر است'); end if;
 select * into r from public.membership_registration_requests where id=p_request_id and building_id=me.building_id and status='pending' for update;
 if not found then return jsonb_build_object('ok',false,'error','درخواست پیدا نشد یا قبلاً بررسی شده است'); end if;
 if p_decision='reject' then
  update public.membership_registration_requests set status='rejected',reviewed_at=now(),reviewed_by=me.id where id=r.id;
  return jsonb_build_object('ok',true,'status','rejected');
 end if;
 if exists(select 1 from public.accounts where lower(username)=lower(r.username)) then
  return jsonb_build_object('ok',false,'error','این نام کاربری در این فاصله استفاده شده است');
 end if;
 if r.occupancy='مالک ساکن' and exists(select 1 from public.accounts where building_id=me.building_id and unit_no=r.unit_no)
  or r.occupancy='مالک' and exists(select 1 from public.accounts where building_id=me.building_id and unit_no=r.unit_no and occupancy in ('مالک','مالک ساکن'))
  or r.occupancy='مستأجر' and exists(select 1 from public.accounts where building_id=me.building_id and unit_no=r.unit_no and occupancy in ('مستأجر','مالک ساکن')) then
  return jsonb_build_object('ok',false,'error','شرایط ظرفیت واحد هنگام تأیید تغییر کرده است');
 end if;
 v_start := substring(r.start_date_jalali from 1 for 4)::integer*100 + substring(r.start_date_jalali from 6 for 2)::integer;
 insert into public.accounts(username,password_hash,unit_no,full_name,phone,email,occupancy,is_admin,is_primary,is_active,must_change_password,start_ym,building_id,role,start_date_jalali)
 values(r.username,r.password_hash,r.unit_no,r.full_name,r.phone,r.email,r.occupancy,false,r.occupancy='مالک ساکن',true,true,v_start,me.building_id,
 case when r.occupancy='مستأجر' then 'tenant' when r.occupancy='مالک' then 'owner' else 'resident_owner' end,r.start_date_jalali)
 returning id into v_id;
 update public.units set area=r.area, persons=case when r.persons is not null then r.persons else persons end, occupancy=r.occupancy, updated_at=now()
 where building_id=me.building_id and unit_no=r.unit_no;
 update public.membership_registration_requests set status='approved',reviewed_at=now(),reviewed_by=me.id where id=r.id;
 return jsonb_build_object('ok',true,'account_id',v_id,'status','approved');
end $$;

create or replace function public.app_superadmin_review_registration(p_token uuid,p_request_id bigint,p_decision text)
returns jsonb language plpgsql security definer set search_path=pg_catalog,public,extensions
as $$
declare r public.registration_requests; v_building integer; v_account uuid; i integer; v_start integer;
begin
 perform public.bm_superadmin_auth(p_token);
 if p_decision not in ('approve','reject') then return jsonb_build_object('ok',false,'error','تصمیم نامعتبر است'); end if;
 select * into r from public.registration_requests where id=p_request_id for update;
 if not found or r.status<>'pending' then return jsonb_build_object('ok',false,'error','درخواست پیدا نشد یا قبلاً بررسی شده است'); end if;
 if p_decision='reject' then
  update public.registration_requests set status='rejected',reviewed_at=now(),reviewed_by=public.bm_superadmin_auth(p_token) where id=r.id;
  return jsonb_build_object('ok',true,'status','rejected');
 end if;
 if r.units_count not between 1 and 10 then return jsonb_build_object('ok',false,'error','تعداد واحدهای درخواست معتبر نیست'); end if;
 if exists(select 1 from public.accounts where lower(username)=lower(r.username)) then
  return jsonb_build_object('ok',false,'error','نام کاربری قبلاً استفاده شده است');
 end if;
 insert into public.buildings(name,address,status,created_by)
 values(r.building_name,r.address,'active',public.bm_superadmin_auth(p_token)) returning id into v_building;
 if r.manager_is_resident then
  v_start:=substring(r.manager_start_date_jalali from 1 for 4)::integer*100+substring(r.manager_start_date_jalali from 6 for 2)::integer;
  insert into public.accounts(username,password_hash,unit_no,full_name,phone,email,occupancy,is_admin,is_primary,is_active,must_change_password,start_ym,building_id,role,start_date_jalali)
  values(r.username,r.password_hash,r.manager_unit_no,r.full_name,r.phone,r.email,'مالک ساکن',true,true,true,true,v_start,v_building,'manager',r.manager_start_date_jalali)
  returning id into v_account;
  for i in 1..r.units_count loop
   insert into public.units(building_id,unit_no,persons,area,occupancy)
   values(v_building,i,case when i=r.manager_unit_no then r.manager_persons else 0 end,
    case when i=r.manager_unit_no then r.manager_area else null end,
    case when i=r.manager_unit_no then 'مالک ساکن' else 'مالک' end);
  end loop;
 else
  insert into public.accounts(username,password_hash,full_name,phone,email,role,is_admin,is_primary,is_active,must_change_password,building_id,unit_no)
  values(r.username,r.password_hash,r.full_name,r.phone,r.email,'manager',true,true,true,true,v_building,null)
  returning id into v_account;
  for i in 1..r.units_count loop
   insert into public.units(building_id,unit_no,persons,occupancy) values(v_building,i,0,'مالک');
  end loop;
 end if;
 update public.buildings set current_manager_account_id=v_account where id=v_building;
 update public.registration_requests set status='approved',reviewed_at=now(),reviewed_by=public.bm_superadmin_auth(p_token) where id=r.id;
 return jsonb_build_object('ok',true,'building_id',v_building,'manager_account_id',v_account,'units_count',r.units_count);
end $$;

create or replace function public.app_login_unified(p_login text,p_password text)
returns jsonb language plpgsql security definer set search_path=pg_catalog,public,extensions
as $$
declare sa public.superadmin_accounts; a public.accounts; v_token uuid; b public.buildings;
begin
 select * into sa from public.superadmin_accounts
 where lower(username)=lower(trim(coalesce(p_login,''))) and is_active limit 1;
 if found and sa.password_hash=extensions.crypt(coalesce(p_password,''),sa.password_hash) then
  insert into public.sessions(building_id,superadmin_id,expires_at) values(null,sa.id,now()+interval '8 hours') returning token into v_token;
  return jsonb_build_object('ok',true,'kind','superadmin','token',v_token,
   'account',jsonb_build_object('id',sa.id,'username',sa.username,'full_name',sa.full_name,'role','superadmin'));
 end if;
 select * into a from public.accounts where lower(username)=lower(trim(coalesce(p_login,''))) limit 1 for update;
 if not found or not a.is_active then return jsonb_build_object('ok',false,'error','نام کاربری یا رمز عبور اشتباه است'); end if;
 if a.locked_until is not null and a.locked_until>now() then return jsonb_build_object('ok',false,'error','حساب موقتاً قفل است'); end if;
 if a.password_hash<>extensions.crypt(coalesce(p_password,''),a.password_hash) then
  update public.accounts set failed_attempts=case when failed_attempts+1>=5 then 0 else failed_attempts+1 end,
   locked_until=case when failed_attempts+1>=5 then now()+interval '10 minutes' else null end where id=a.id;
  return jsonb_build_object('ok',false,'error','نام کاربری یا رمز عبور اشتباه است');
 end if;
 update public.accounts set failed_attempts=0,locked_until=null where id=a.id;
 select * into b from public.buildings where id=a.building_id and status='active';
 if not found then return jsonb_build_object('ok',false,'error','ساختمان حساب کاربری فعال نیست'); end if;
 insert into public.sessions(account_id,building_id,expires_at) values(a.id,a.building_id,now()+interval '7 days') returning token into v_token;
 insert into public.activity_logs(building_id,account_id,unit_no,full_name,action,details,actor_id)
 values(a.building_id,a.id,a.unit_no,a.full_name,'ورود','ورود موفق',a.id);
 return jsonb_build_object('ok',true,'kind','building','token',v_token,
  'account',public.bm_account_json(a)||jsonb_build_object('building_name',b.name,'units_count',(select count(*) from public.units where building_id=a.building_id)));
end $$;

