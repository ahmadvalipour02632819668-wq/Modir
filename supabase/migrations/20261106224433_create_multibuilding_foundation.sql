
create table public.buildings (
 id integer generated by default as identity primary key,
 name text not null,
 address text,
 status text not null default 'pending' check (status in ('pending','active','suspended','deleted')),
 created_at timestamptz not null default now(),
 current_manager_account_id uuid,
 created_by uuid
);
create table public.accounts (
 id uuid primary key default gen_random_uuid(),
 username text not null,
 password_hash text not null,
 unit_no integer,
 full_name text,
 phone text,
 email text,
 occupancy text not null default 'مالک ساکن',
 is_admin boolean not null default false,
 is_primary boolean not null default true,
 is_active boolean not null default true,
 must_change_password boolean not null default true,
 failed_attempts integer not null default 0,
 locked_until timestamptz,
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now(),
 start_ym integer default 140406,
 building_id integer not null references public.buildings(id),
 role text not null default 'resident' check (role in ('resident','manager','superadmin')),
 unique(building_id,username)
);
create table public.units (
 unit_no integer not null,
 persons integer not null default 0,
 area numeric,
 occupancy text not null default 'مالک ساکن',
 has_parking boolean not null default false,
 notes text,
 updated_at timestamptz not null default now(),
 building_id integer not null references public.buildings(id),
 primary key(building_id,unit_no)
);
create table public.transactions (
 id bigint generated by default as identity primary key,
 tx_date text, year integer not null, month integer not null, day integer not null default 1,
 ym integer generated always as (year*100+month) stored,
 month_name text, unit_no integer, tx_type text not null, location text, description text,
 amount bigint not null, occupancy text, category text not null, source text not null default 'manual',
 payment_request_id bigint, created_by uuid, created_at timestamptz not null default now(),
 building_id integer not null references public.buildings(id),
 pay_date text, ref_code text, note text, receipt_image text
);
create table public.rates (
 building_id integer not null references public.buildings(id),
 year integer not null, month integer not null,
 ym integer generated always as (year*100+month) stored,
 charge bigint not null default 0, repair bigint not null default 0, parking bigint not null default 0,
 payer_charge text[] default array['مالک ساکن','مالک','مستأجر'],
 payer_water text[] default array['مالک ساکن','مالک','مستأجر'],
 payer_gas text[] default array['مالک ساکن','مالک','مستأجر'],
 payer_repair text[] default array['مالک ساکن','مالک','مستأجر'],
 payer_parking text[] default array['مالک ساکن','مالک','مستأجر'],
 primary key(building_id,year,month)
);
create table public.settings(building_id integer not null references public.buildings(id), key text not null, value text not null, primary key(building_id,key));
create table public.exemptions(building_id integer not null references public.buildings(id), unit_no integer not null, category text not null, primary key(building_id,unit_no,category));
create table public.announcements(id bigint generated by default as identity primary key, building_id integer not null references public.buildings(id), title text not null, content text not null, type text default 'general', created_at timestamptz default now());
create table public.payment_requests(
 id bigint generated by default as identity primary key, building_id integer not null references public.buildings(id),
 account_id uuid, unit_no integer not null, year integer not null, month integer not null, category text not null,
 amount bigint not null, pay_date text, ref_code text, note text, status text not null default 'pending',
 admin_note text, reviewed_by uuid, reviewed_at timestamptz, created_at timestamptz not null default now(), receipt_image text
);
create table public.resident_requests(
 id bigint generated by default as identity primary key, building_id integer not null references public.buildings(id),
 account_id uuid, unit_no integer, type text not null, description text not null, status text default 'pending',
 created_at timestamptz default now(), admin_reply text, replied_at timestamptz, replied_by text
);
create table public.activity_logs(
 id bigint generated by default as identity primary key, building_id integer not null references public.buildings(id),
 account_id uuid, unit_no integer, full_name text, action text, created_at timestamptz default now(),
 details text, actor_id uuid
);
create table public.sessions(
 token uuid primary key default gen_random_uuid(), account_id uuid not null references public.accounts(id),
 building_id integer not null references public.buildings(id), created_at timestamptz not null default now(),
 expires_at timestamptz not null default now()+interval '7 days', revoked_at timestamptz
);
create table public.profile_avatars(account_id uuid primary key references public.accounts(id), image_data text not null, updated_at timestamptz not null default now());
create table public.push_subscriptions(
 id uuid primary key default gen_random_uuid(), account_id uuid not null references public.accounts(id),
 building_id integer not null references public.buildings(id), endpoint text not null unique,
 p256dh text not null, auth text not null, user_agent text, created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table public.building_polls(id bigint generated by default as identity primary key, building_id integer not null references public.buildings(id), title text not null, description text not null default '', is_active boolean not null default true, created_by uuid, created_at timestamptz not null default now());
create table public.building_poll_options(id bigint generated by default as identity primary key, poll_id bigint not null references public.building_polls(id) on delete cascade, option_text text not null, sort_order integer not null default 0);
create table public.building_poll_votes(id bigint generated by default as identity primary key, poll_id bigint not null references public.building_polls(id) on delete cascade, option_id bigint not null references public.building_poll_options(id) on delete cascade, account_id uuid not null references public.accounts(id), created_at timestamptz not null default now(), unique(poll_id,account_id));
create table public.management_transfer_requests(id bigint generated by default as identity primary key, building_id integer not null references public.buildings(id), requested_by uuid not null references public.accounts(id), target_account_id uuid not null references public.accounts(id), status text not null default 'pending', created_at timestamptz not null default now(), responded_at timestamptz);
create table public.receipts(id uuid primary key default gen_random_uuid(), building_id integer not null references public.buildings(id), unit_no integer not null, status text not null default 'pending', pay_date date not null, tracking_no text not null, total bigint not null, image_path text, note text, admin_note text, decided_by uuid, decided_at timestamptz, created_at timestamptz not null default now());
create table public.receipt_lines(id bigint generated by default as identity primary key, receipt_id uuid not null references public.receipts(id) on delete cascade, year integer not null, month integer not null, place text not null, description text not null, amount bigint not null);
create table public.ledger(id bigint generated by default as identity primary key, building_id integer not null references public.buildings(id), entry_date date not null, year integer not null, month integer not null, unit_no integer, type text not null, place text not null, description text not null, amount bigint not null, residency text, receipt_id uuid, created_at timestamptz not null default now());
create table public.registration_requests(
 id bigint generated by default as identity primary key, building_name text not null, address text not null,
 username text not null, password_hash text not null, full_name text not null, phone text, email text,
 units_count integer not null check(units_count between 1 and 99), status text not null default 'pending' check(status in ('pending','approved','rejected')),
 reviewed_at timestamptz, reviewed_by uuid, created_at timestamptz not null default now()
);
create table public.superadmin_accounts(id uuid primary key default gen_random_uuid(), username text unique not null, password_hash text not null, full_name text, is_active boolean not null default true, created_at timestamptz not null default now());
create index accounts_building_unit_idx on public.accounts(building_id,unit_no);
create index transactions_building_period_idx on public.transactions(building_id,year,month);
create index payment_requests_building_status_idx on public.payment_requests(building_id,status);

